import { mkdir, readFile, readdir, rename, rm, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MARKER = "<!-- Generated by scripts/render-compendium.mjs. Edit data/compendium.json. -->";
const OWNER = "compendium";
const [entries, config, pages, sitemap, siteMap] = await Promise.all([
    readFile(path.join(ROOT, "data/compendium.json"), "utf8").then(JSON.parse),
    readFile(path.join(ROOT, "data/config.json"), "utf8").then(JSON.parse),
    readFile(path.join(ROOT, "data/pages.json"), "utf8").then(JSON.parse),
    readFile(path.join(ROOT, "sitemaps/sitemap-pages.xml"), "utf8"),
    readFile(path.join(ROOT, "site-map/index.html"), "utf8")
]);

function escape(value) {
    return String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;")
        .replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

async function readOptional(file) {
    try {
        return await readFile(path.join(ROOT, file), "utf8");
    } catch (error) {
        if (error.code === "ENOENT") return "";
        throw error;
    }
}

function entryUrl(entry) {
    return `/compendium/${entry.slug}/`;
}

function requireStrings(values, label) {
    if (!Array.isArray(values) || values.some(value => typeof value !== "string" || !value.trim())) {
        throw new Error(`${label} must be an array of nonempty strings.`);
    }
}

function validHref(value) {
    return typeof value === "string" && (value === "/" || /^(https:\/\/|\/(?![\/\\]))[^\s]+$/.test(value));
}

if (!Array.isArray(entries) || entries.length === 0) {
    throw new Error("data/compendium.json must contain at least one entry.");
}
const slugs = new Set();
for (const entry of entries) {
    if (typeof entry.slug !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.slug) || slugs.has(entry.slug)) {
        throw new Error(`Each Compendium entry needs a unique, lowercase slug. Check ${entry.slug}.`);
    }
    slugs.add(entry.slug);
    for (const key of ["term", "definition"]) {
        if (typeof entry[key] !== "string" || !entry[key].trim()) {
            throw new Error(`${entry.slug} needs a ${key}.`);
        }
    }
    for (const key of ["tags", "context", "examples", "aliases", "related"]) {
        requireStrings(entry[key] || [], `${entry.slug}.${key}`);
    }
    if (!Array.isArray(entry.sections ?? [])) {
        throw new Error(`${entry.slug}.sections must be an array.`);
    }
    const sectionIds = new Set();
    for (const section of entry.sections || []) {
        if (!section || typeof section.id !== "string"
            || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(section.id)
            || sectionIds.has(section.id)
            || typeof section.title !== "string" || !section.title.trim()) {
            throw new Error(`${entry.slug} needs valid sections with unique lowercase ids and nonempty titles.`);
        }
        sectionIds.add(section.id);
        requireStrings(section.paragraphs ?? [], `${entry.slug}.sections.${section.id}.paragraphs`);
        requireStrings(section.items ?? [], `${entry.slug}.sections.${section.id}.items`);
        if (!(section.paragraphs?.length || section.items?.length)) {
            throw new Error(`${entry.slug}.sections.${section.id} needs at least one paragraph or list item.`);
        }
    }
    if (!Array.isArray(entry.references || [])) {
        throw new Error(`${entry.slug}.references must be an array.`);
    }
    for (const reference of entry.references || []) {
        if (typeof reference.label !== "string" || !reference.label.trim()
            || !validHref(reference.href)) {
            throw new Error(`${entry.slug} has an invalid reference. Use a label and an HTTPS or root-relative href.`);
        }
    }
    if (!Array.isArray(entry.links || [])) throw new Error(`${entry.slug}.links must be an array.`);
    const linkLabels = new Set();
    for (const link of entry.links || []) {
        if (typeof link.text !== "string" || !link.text.trim() || !validHref(link.href)
            || linkLabels.has(link.text.toLowerCase())
            || (link.cite !== undefined && typeof link.cite !== "boolean")
            || (link.quote !== undefined && typeof link.quote !== "boolean")
            || (link.caseSensitive !== undefined && typeof link.caseSensitive !== "boolean")) {
            throw new Error(`${entry.slug} has an invalid or duplicate inline link.`);
        }
        linkLabels.add(link.text.toLowerCase());
    }
    if (entry.image) {
        const image = entry.image;
        if (typeof image.src !== "string" || !image.src.startsWith("/assets/")
            || !/\.(png|jpe?g|webp|gif|svg)$/i.test(image.src)
            || !path.resolve(ROOT, image.src.slice(1)).startsWith(path.join(ROOT, "assets") + path.sep)
            || typeof image.alt !== "string" || !image.alt.trim()
            || typeof image.caption !== "string" || !image.caption.trim()
            || !Number.isInteger(image.width) || image.width < 1
            || !Number.isInteger(image.height) || image.height < 1
            || (image.credit && (!image.credit.label || !validHref(image.credit.href)))
            || (image.license && (!image.license.label || !validHref(image.license.href)))) {
            throw new Error(`${entry.slug} needs a valid local image, dimensions, caption, and credit.`);
        }
        await readFile(path.join(ROOT, image.src.slice(1)));
    }
}
for (const entry of entries) {
    for (const slug of entry.related || []) {
        if (!slugs.has(slug) || slug === entry.slug) {
            throw new Error(`${entry.slug} has an invalid related entry, ${slug}.`);
        }
    }
    for (const link of entry.links || []) {
        const match = link.href.match(/^\/compendium\/([a-z0-9-]+)\/(?:#.*)?$/);
        if (match && !slugs.has(match[1])) {
            throw new Error(`${entry.slug} links to an unknown Compendium entry, ${match[1]}.`);
        }
    }
}
entries.sort((a, b) => a.term.replace(/^The /, "").localeCompare(b.term.replace(/^The /, ""), "en"));
const bySlug = new Map(entries.map(entry => [entry.slug, entry]));

function tags(entry) {
    const items = (entry.tags || []).map(tag =>
        `<li><a class="compendium-tag" data-compendium-tag="${escape(tag)}" href="/compendium/?tag=${encodeURIComponent(tag)}">${escape(tag)}</a></li>`
    ).join("\n");
    return `<ul class="compendium-tags" aria-label="Tags">\n${items}\n</ul>`;
}

function shareButton(entry) {
    return `<button class="compendium-share-button" type="button" data-compendium-share="${entryUrl(entry)}" data-share-term="${escape(entry.term)}" aria-label="Share ${escape(entry.term)}" title="Share ${escape(entry.term)}" hidden><svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="M12 15V3m-4 4 4-4 4 4M5 13v6a2 2 0 0 0 2 2h10a2 2 0 0 0 2-2v-6"/></svg></button>`;
}

function linkedText(text, entry) {
    const links = (entry.links || []).slice().sort((a, b) => b.text.length - a.text.length);
    if (links.length === 0) return escape(text);
    const byText = new Map(links.map(link => [link.text.toLowerCase(), link]));
    const phrases = links.map(link => link.text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
    const pattern = new RegExp(`(?<![\\p{L}\\p{N}_])(?:${phrases.join("|")})(?![\\p{L}\\p{N}_])`, "giu");
    let result = "";
    let previous = 0;
    for (const match of text.matchAll(pattern)) {
        const link = byText.get(match[0].toLowerCase());
        let label = escape(match[0]);
        if (!link.caseSensitive || match[0] === link.text) {
            if (link.cite) label = `<cite>${label}</cite>`;
            label = `<a href="${escape(link.href)}">${label}</a>`;
            if (link.quote) label = `“${label}”`;
        }
        result += escape(text.slice(previous, match.index)) + label;
        previous = match.index + match[0].length;
    }
    return result + escape(text.slice(previous));
}

function renderImage(entry) {
    const image = entry.image;
    if (!image) return "";
    const credit = image.credit ? `<a href="${escape(image.credit.href)}">${escape(image.credit.label)}</a>` : "";
    const license = image.license ? ` · <a href="${escape(image.license.href)}">${escape(image.license.label)}</a>` : "";
    return `<figure class="compendium-image"><img src="${escape(image.src)}" alt="${escape(image.alt)}" width="${image.width}" height="${image.height}" loading="lazy" decoding="async"><figcaption>${linkedText(image.caption, entry)}${credit ? `<span class="compendium-image-credit">${credit}${license}</span>` : ""}</figcaption></figure>`;
}

const shareDialog = `<dialog class="compendium-share-dialog" aria-labelledby="compendium-share-title">
    <form method="dialog"><button class="compendium-close" aria-label="Close sharing options">Close</button></form>
    <h2 id="compendium-share-title">Share entry</h2>
    <label for="compendium-share-url">Link to this entry</label>
    <input id="compendium-share-url" type="url" readonly>
    <button class="cta-button" type="button" data-compendium-copy autofocus>Copy link</button>
    <p class="compendium-share-status" role="status" aria-live="polite"></p>
</dialog>`;

function renderIndex() {
    const items = entries.map(entry => `
        <li class="compendium-entry" id="${entry.slug}" data-aliases="${escape((entry.aliases || []).join(" "))}">
            <div class="compendium-entry-line">
                ${shareButton(entry)}
                <p class="compendium-summary"><a class="compendium-term" href="${entryUrl(entry)}">${escape(entry.term)}</a>: ${escape(entry.definition)}</p>
            </div>
            ${tags(entry)}
        </li>`).join("\n");
    return `
        <div class="compendium-heading">
            <h1 id="compendium-title">Compendium</h1>
            <p>A glossary of terms from my writing and projects. Select a term for examples, context, and references.</p>
        </div>

        <section class="section compendium-panel" aria-labelledby="compendium-title">
            <div class="compendium-tools" hidden>
                <div role="search" aria-label="Search the Compendium">
                    <label for="compendium-search">Search the Compendium</label>
                    <input id="compendium-search" type="search" placeholder="Search terms, definitions, or tags">
                </div>
                <fieldset class="compendium-filters">
                    <legend>Filter by tag</legend>
                    <p class="compendium-filter-help" id="compendium-filter-help">Match any selected tag.</p>
                    <div class="compendium-filter-options" aria-describedby="compendium-filter-help"></div>
                </fieldset>
                <div class="compendium-results">
                    <p class="compendium-result-count" role="status"></p>
                    <button class="compendium-reset" type="button" hidden>Clear search and tags</button>
                </div>
            </div>
            <ul class="compendium-entries" aria-label="Compendium entries">${items}
            </ul>
        </section>`;
}

function renderEntry(entry) {
    const paragraphs = (entry.context || []).map(text => `<p>${linkedText(text, entry)}</p>`).join("\n");
    const sections = (entry.sections || []).map(section => {
        const id = `entry-section-${section.id}`;
        const body = (section.paragraphs || []).map(text => `<p>${linkedText(text, entry)}</p>`).join("\n");
        const items = (section.items || []).map(text => `<li>${linkedText(text, entry)}</li>`).join("\n");
        return `<section class="compendium-section" aria-labelledby="${id}"><h2 id="${id}">${escape(section.title)}</h2>\n${body}${items ? `\n<ul>\n${items}\n</ul>` : ""}</section>`;
    }).join("\n");
    const examples = (entry.examples || []).map(text => `<li>${linkedText(text, entry)}</li>`).join("\n");
    const references = (entry.references || []).map(reference =>
        `<li><a href="${escape(reference.href)}">${escape(reference.label)}</a></li>`
    ).join("\n");
    const related = (entry.related || []).map(slug => {
        const other = bySlug.get(slug);
        return `<li><a href="${entryUrl(other)}">${escape(other.term)}</a></li>`;
    }).join("\n");

    return `
        <article class="section compendium-detail">
            <div class="compendium-detail-heading">
                <h1 id="compendium-title">${escape(entry.term)}</h1>
                ${shareButton(entry)}
            </div>
            <p class="compendium-definition">${linkedText(entry.definition, entry)}</p>
            ${tags(entry)}
            ${renderImage(entry)}
            ${paragraphs ? `<section class="compendium-section" aria-labelledby="context-title"><h2 id="context-title">Context</h2>\n${paragraphs}</section>` : ""}${sections ? `\n            ${sections}` : ""}
            ${examples ? `<section class="compendium-section" aria-labelledby="examples-title"><h2 id="examples-title">Examples</h2><ul>\n${examples}\n</ul></section>` : ""}
            ${references ? `<section class="compendium-section" aria-labelledby="references-title"><h2 id="references-title">References</h2><ul>\n${references}\n</ul></section>` : ""}
            ${related ? `<nav class="compendium-section" aria-labelledby="related-title"><h2 id="related-title">Related entries</h2><ul class="compendium-related">\n${related}\n</ul></nav>` : ""}
            <p class="compendium-back"><a href="/compendium/">← Browse the Compendium</a></p>
        </article>`;
}

function renderDocument(previous, content, entry) {
    const head = previous.match(/<head\b[^>]*>[\s\S]*?<\/head>/i)?.[0] || "<head>\n</head>";
    const crumbs = entry
        ? `<li><a href="/compendium/">Compendium</a></li><li aria-current="page">${escape(entry.term)}</li>`
        : '<li aria-current="page">Compendium</li>';
    return `<!DOCTYPE html>
<html lang="en">
${MARKER}
${head}
<body class="compendium-page">
    <div id="header-placeholder"></div>
    <main class="container compendium-main">
        <nav class="breadcrumbs" aria-label="Breadcrumb">
            <ol><li><a href="/">Home</a></li>${crumbs}</ol>
        </nav>
${content}
        ${shareDialog}
    </main>
    <div id="footer-placeholder"></div>
</body>
</html>
`.replace(/^[ \t]+$/gm, "");
}

function replaceBlock(source, name, content) {
    const start = `<!-- ${name}: start -->`;
    const end = `<!-- ${name}: end -->`;
    const begin = source.indexOf(start);
    const finish = source.indexOf(end, begin + start.length);
    if (begin < 0 || finish < 0 || source.indexOf(start, begin + start.length) >= 0) {
        throw new Error(`Expected one ${name} block.`);
    }
    const indent = source.slice(source.lastIndexOf("\n", begin) + 1, begin);
    return source.slice(0, begin + start.length) + "\n" + content + "\n" + indent + source.slice(finish);
}

const updates = new Map();
const registered = Object.entries(pages).filter(([, page]) => page.generatedBy === OWNER);
const generatedMetadata = {};
for (const entry of entries) {
    const url = entryUrl(entry);
    const file = `${url.slice(1)}index.html`;
    const previous = await readOptional(file);
    if ((previous && !previous.includes(MARKER))
        || (pages[url] && pages[url].generatedBy !== OWNER)) {
        throw new Error(`${file} already has manually maintained content. Choose another slug.`);
    }
    updates.set(file, renderDocument(previous, renderEntry(entry), entry));
    generatedMetadata[url] = {
        title: `${entry.term} | ${config.siteName}`,
        description: entry.definition,
        breadcrumbLabel: entry.term,
        extraScripts: ["/assets/js/pages/compendium.js"],
        ...(entry.image && entry.image.width >= 300 && entry.image.height >= 200 ? { image: {
            url: entry.image.src,
            type: { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp", gif: "image/gif", svg: "image/svg+xml" }[entry.image.src.split(".").pop().toLowerCase()],
            width: entry.image.width,
            height: entry.image.height,
            alt: entry.image.alt
        } } : {}),
        generatedBy: OWNER
    };
}

// Only remove stale pages that this generator owns.
const staleFiles = [];
const directories = await readdir(path.join(ROOT, "compendium"), { withFileTypes: true });
for (const directory of directories.filter(item => item.isDirectory())) {
    const file = `compendium/${directory.name}/index.html`;
    const previous = await readOptional(file);
    if (!slugs.has(directory.name) && previous.includes(MARKER)) staleFiles.push(file);
}
for (const [url] of registered) {
    if (!/^\/compendium\/[a-z0-9-]+\/$/.test(url)) {
        throw new Error(`Unexpected generated Compendium route, ${url}.`);
    }
    const previous = await readOptional(`${url.slice(1)}index.html`);
    if (previous && !previous.includes(MARKER)) {
        throw new Error(`${url} contains manually maintained content. Resolve it before generating.`);
    }
}

const nextPages = {};
for (const [url, page] of Object.entries(pages)) {
    if (page.generatedBy === OWNER) continue;
    nextPages[url] = page;
    if (url === "/compendium/") Object.assign(nextPages, generatedMetadata);
}
if (!nextPages["/compendium/"]) throw new Error("Register /compendium/ in data/pages.json first.");
updates.set("data/pages.json", JSON.stringify(nextPages, null, 4) + "\n");
const currentIndex = await readOptional("compendium/index.html");
updates.set("compendium/index.html", renderDocument(currentIndex, renderIndex()));

const sitemapLinks = entries.map(entry =>
    `    <url><loc>${escape(new URL(entryUrl(entry), config.baseUrl).href)}</loc></url>`
).join("\n");
updates.set("sitemaps/sitemap-pages.xml", replaceBlock(sitemap, "Compendium sitemap", sitemapLinks));
const siteLinks = entries.map(entry =>
    `                <li><span class="text-small">├┤</span> <a href="${entryUrl(entry)}">${escape(entry.term)}</a></li>`
).join("\n");
if (siteMap.includes("<!-- Compendium entries: start -->") &&
        siteMap.includes("<!-- Compendium entries: end -->")) {
    updates.set(
        "site-map/index.html",
        replaceBlock(siteMap, "Compendium entries", siteLinks)
    );
}

// Validate and render the entire collection before writing any source files.
// A repeated run repairs an interrupted generation without touching other pages.
let changed = 0;
for (const [file, text] of updates) {
    if (await readOptional(file) === text) continue;
    const absolute = path.join(ROOT, file);
    await mkdir(path.dirname(absolute), { recursive: true });
    const temporary = `${absolute}.${randomUUID()}.tmp`;
    try {
        await writeFile(temporary, text, { encoding: "utf8", flag: "wx" });
        await rename(temporary, absolute);
    } finally {
        await rm(temporary, { force: true });
    }
    changed++;
}
for (const file of staleFiles) await rm(path.join(ROOT, file), { force: true });
console.log(`Rendered the Compendium and ${entries.length} entry pages (${changed} files updated).`);
